/**
 * Writes the privacy policy and terms of use to the website (site/privacy, site/terms) from
 * the same text the app shows (src/content/legal.ts), so the two never drift apart, plus the
 * account deletion guide Google Play links to (site/delete-account). The English versions
 * (src/content/legal.en.ts) go to site/en/privacy, site/en/terms and site/en/delete-account.
 *
 *   npx tsx scripts/build-legal.ts
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

import { ACCOUNT_DELETION, LEGAL, LEGAL_UPDATED, type LegalDoc } from '../src/content/legal';
import { ACCOUNT_DELETION_EN, LEGAL_EN, LEGAL_UPDATED_EN } from '../src/content/legal.en';

const ROOT = resolve(__dirname, '..');

const escape = (s: string) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

export type SiteLang = 'fa' | 'en';

type SitePage = Pick<LegalDoc, 'title' | 'intro' | 'sections'> & { id: string; english?: string[] };

/** Per language: the page chrome, and where the pages sit (`base`) and the site root is (`root`) from them. */
const UI = {
  fa: {
    dir: 'rtl',
    brand: 'چارتون',
    app: 'ورود به اپ',
    updated: `آخرین به‌روزرسانی: ${LEGAL_UPDATED}`,
    home: 'صفحه‌ی اصلی',
    courses: 'دوره‌ها',
    copyright: '© ۱۴۰۵ چارتون',
    other: { lang: 'en', label: 'English', href: (id: string) => `../en/${id}/` },
    base: '',
    root: '../',
    legal: LEGAL,
    deletion: ACCOUNT_DELETION,
  },
  en: {
    dir: 'ltr',
    brand: 'Chartoon',
    app: 'Open the app',
    updated: `Last updated: ${LEGAL_UPDATED_EN}`,
    home: 'Home',
    courses: 'Courses',
    copyright: '© 2026 Chartoon',
    other: { lang: 'fa', label: 'فارسی', href: (id: string) => `../../${id}/` },
    base: 'en/',
    root: '../../',
    legal: LEGAL_EN,
    deletion: ACCOUNT_DELETION_EN,
  },
};

export function legalPage(doc: LegalDoc, lang: SiteLang = 'fa'): string {
  const { legal, deletion } = UI[lang];
  return sitePage(doc, [legal[doc.id === 'privacy' ? 'terms' : 'privacy'], { id: deletion.id, title: deletion.title }], lang);
}

export function deletionPage(lang: SiteLang = 'fa'): string {
  const { legal, deletion } = UI[lang];
  return sitePage(deletion, [legal.privacy, legal.terms], lang);
}

