export function writeLegalPages(siteDir = join(ROOT, 'site')) {
  const written: string[] = [];
  for (const lang of ['fa', 'en'] as const) {
    const { base, legal, deletion } = UI[lang];
    const pages: [string, string][] = [...Object.values(legal).map((doc): [string, string] => [doc.id, legalPage(doc, lang)]), [deletion.id, deletionPage(lang)]];
    for (const [id, html] of pages) {
      mkdirSync(join(siteDir, base, id), { recursive: true });
      writeFileSync(join(siteDir, base, id, 'index.html'), html);
      written.push(`site/${base}${id}/index.html`);
    }
  }
  return written;
}

